"""Table of the related work that compares the closest studies on their protocol.

paper/related_studies.yaml holds, for each study read in full text, the value of each
column and the passages of the paper that support it (verbatim, with their page). The
table of the article is generated from this file; a cell without a supporting passage
reads "not stated". `check_quotes` verifies that every passage is in the text extracted
from the paper, when this text is on the machine (paper/refs/fulltext/, not versioned:
the papers are not ours to redistribute).
"""

import re
from pathlib import Path

import yaml

from src.eval import latex

NOT_STATED = "not stated"
MAX_QUOTE = 300   # characters of a supporting passage


def load(path: Path) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def squeeze(text: str) -> str:
    """Text with every run of white space reduced to one space: a passage cut by a line break still matches."""
    return re.sub(r"\s+", " ", text).strip()


def problems(spec: dict) -> list[str]:
    """What is wrong in the file itself: a missing column, a value without a passage, a passage too long."""
    found = []
    for key, study in spec["studies"].items():
        for column in spec["columns"]:
            cell = study.get(column)
            if not cell or not cell.get("value"):
                found.append(f"{key}.{column}: no value")
                continue
            quotes = cell.get("quotes") or []
            if cell["value"] != NOT_STATED and not quotes and not cell.get("read_whole_section"):
                found.append(f"{key}.{column}: a value without a supporting passage")
            found += [f"{key}.{column}: passage of more than {MAX_QUOTE} characters" for q in quotes if len(q["text"]) > MAX_QUOTE]
    return found


def check_quotes(spec: dict, fulltext: Path) -> tuple[list[str], int]:
    """Passages that are not in the extracted text of their paper, and the number of passages checked.
    A study whose text is not on the machine is skipped."""
    missing, checked = [], 0
    for key, study in spec["studies"].items():
        source = fulltext / f"{key}.txt"
        if not source.is_file():
            continue
        pages = re.split(r"=== page (\d+) ===", source.read_text(encoding="utf-8", errors="replace"))
        text = {int(number): squeeze(body) for number, body in zip(pages[1::2], pages[2::2])}
        for column, cell in study.items():
            for quote in (cell.get("quotes") or []) if isinstance(cell, dict) else []:
                checked += 1
                # a passage may run over a page break: it is looked for in its page and the next one
                where = text.get(quote["page"], "") + " " + text.get(quote["page"] + 1, "")
                if squeeze(quote["text"]) not in where:
                    missing.append(f"{key}.{column}, page {quote['page']}: {quote['text'][:70]}")
    return missing, checked


def authors(record: dict) -> str:
    names = [author["family"] for author in record["authors"]]
    return names[0] if len(names) == 1 else f"{names[0]} and {names[1]}" if len(names) == 2 else f"{names[0]} et al."


def render(spec: dict, records: dict) -> str:
    """The LaTeX table: one row per study read in full text, then the present study."""
    unknown = [key for key in [*spec["studies"], *spec["not_read"]] if key not in records]
    if unknown:
        raise ValueError(f"not in paper/references.json: {unknown}")
    columns = spec["columns"]
    widths = spec["widths_mm"]
    align = "".join(rf">{{\raggedright\arraybackslash}}p{{{widths[name]}mm}}" for name in ["study", *columns])
    rows = [[rf"{latex.escape(authors(records[key]))}~\cite{{{key}}}", *[latex.escape(study[name]["value"]) for name in columns]]
            for key, study in spec["studies"].items()]
    rows += [None, ["This study", *[latex.escape(spec["this_study"][name]) for name in columns]]]
    caption = (f"{spec['caption']} Each cell of a cited study is supported by a passage of its full text; "
               f"``{NOT_STATED}'' means that the paper gives no such information. "
               rf"Closely related studies whose full text was not available to us are not in the table~\cite{{{','.join(spec['not_read'])}}}.")
    header = ["Study", *[latex.escape(heading) for heading in columns.values()]]
    text = latex.table(header, rows, caption, "tab:related", align=align, size="footnotesize", gap=3)
    return ("% Generated by scripts/11_paper.py from paper/related_studies.yaml. Do not edit.\n"
            + text.replace(r"\begin{table}[t]", r"\begin{table}[!tp]"))
